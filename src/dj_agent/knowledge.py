# ---------------------------------------------------------------------------
# Build plain-text documents for embedding
# ---------------------------------------------------------------------------

def build_knowledge_texts() -> list[dict]:
    """Return all DJ knowledge as plain dicts for vector indexing.

    Each dict has: {"text": ..., "type": ..., "title": ...}
    """
    docs: list[dict] = []

    for num, text in THEORIES:
        docs.append({
            "text": f"ทฤษฎี Don Juan ข้อที่ {num}: {text}",
            "type": "theory",
            "title": f"Theory {num}",
        })

    for name, text in TECHNIQUES:
        docs.append({
            "text": f"เทคนิค DJ — {name}: {text}",
            "type": "technique",
            "title": name,
        })

    for name, text in RED_FLAGS:
        docs.append({
            "text": f"Red flag / pattern — {name}: {text}",
            "type": "red_flag",
            "title": name,
        })

    return docs
